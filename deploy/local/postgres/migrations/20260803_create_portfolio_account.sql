CREATE TABLE IF NOT EXISTS cynexus_appl_market.portfolio_account (
    id bigint PRIMARY KEY GENERATED BY DEFAULT AS IDENTITY,
    principal_key text NOT NULL,
    tenant_key text NOT NULL,
    available_cash numeric(24,8) NOT NULL DEFAULT 0,
    updated_at timestamptz NOT NULL DEFAULT now(),
    created_at timestamptz NOT NULL DEFAULT now(),
    deleted_at timestamptz,
    CONSTRAINT ck_portfolio_account_available_cash CHECK (available_cash >= 0)
);

CREATE UNIQUE INDEX IF NOT EXISTS uk_portfolio_account_owner
    ON cynexus_appl_market.portfolio_account (principal_key, tenant_key)
    WHERE deleted_at IS NULL;
