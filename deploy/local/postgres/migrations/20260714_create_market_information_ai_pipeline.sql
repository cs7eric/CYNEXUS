        CHECK (status IN ('ready', 'failed', 'needs_ocr', 'unsupported')),
    CONSTRAINT ck_market_information_content_quality
        CHECK (content_quality IN ('full_text', 'summary_only', 'ocr')),
    CONSTRAINT uk_market_information_content_identity
        UNIQUE (source, source_record_id, content_hash)
);

CREATE INDEX IF NOT EXISTS idx_market_information_content_latest
    ON cynexus_appl_market.market_information_content_cache (source, source_record_id, updated_at DESC);

CREATE TABLE IF NOT EXISTS cynexus_appl_market.market_information_event_cluster (
    id bigint PRIMARY KEY,
    cluster_key varchar(96) NOT NULL UNIQUE,
    representative_source varchar(96) NOT NULL,
    representative_record_id varchar(192) NOT NULL,
    normalized_title text NOT NULL,
    display_title text NOT NULL,
    category varchar(32) NOT NULL,
    entities jsonb NOT NULL DEFAULT '[]'::jsonb,
