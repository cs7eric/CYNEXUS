    last_failed_at timestamptz,
    failure_message text,
    updated_at timestamptz NOT NULL DEFAULT now()
);

CREATE TABLE IF NOT EXISTS cynexus_appl_ai.market_information_ai_task (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    task_type varchar(32) NOT NULL,
    cluster_id bigint,
    cluster_content_hash varchar(64),
    task_status varchar(24) NOT NULL DEFAULT 'PENDING',
    priority integer NOT NULL DEFAULT 0,
    attempt_count integer NOT NULL DEFAULT 0,
    max_attempts integer NOT NULL DEFAULT 3,
    next_attempt_at timestamptz NOT NULL DEFAULT now(),
    claimed_at timestamptz,
    claimed_by varchar(128),
    last_error text,
    requested_by varchar(64) NOT NULL DEFAULT 'system',
    created_at timestamptz NOT NULL DEFAULT now(),
    updated_at timestamptz NOT NULL DEFAULT now(),
    CONSTRAINT ck_market_information_ai_task_type CHECK (task_type IN ('EVENT_ANALYSIS', 'DAILY_BRIEF')),
    CONSTRAINT ck_market_information_ai_task_status CHECK (task_status IN ('PENDING', 'RUNNING', 'SUCCEEDED', 'FAILED'))
);

CREATE UNIQUE INDEX IF NOT EXISTS uk_market_information_ai_task_active
    ON cynexus_appl_ai.market_information_ai_task (task_type, coalesce(cluster_id, 0), coalesce(cluster_content_hash, ''))
    WHERE task_status IN ('PENDING', 'RUNNING');

CREATE INDEX IF NOT EXISTS idx_market_information_ai_task_claim
    ON cynexus_appl_ai.market_information_ai_task (task_status, next_attempt_at, priority DESC, created_at);

CREATE TABLE IF NOT EXISTS cynexus_appl_ai.market_information_event_analysis (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    cluster_id bigint NOT NULL,
