);

CREATE INDEX IF NOT EXISTS idx_market_information_analysis_cluster_latest
    ON cynexus_appl_ai.market_information_event_analysis (cluster_id, created_at DESC);

CREATE TABLE IF NOT EXISTS cynexus_appl_ai.market_information_daily_brief (
