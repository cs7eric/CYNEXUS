    member_count integer NOT NULL DEFAULT 1,
    priority_score numeric(8, 3) NOT NULL DEFAULT 0,
    high_value boolean NOT NULL DEFAULT false,
    content_hash varchar(64) NOT NULL,
    created_at timestamptz NOT NULL DEFAULT now(),
    updated_at timestamptz NOT NULL DEFAULT now()
);

CREATE INDEX IF NOT EXISTS idx_market_information_cluster_priority
    ON cynexus_appl_market.market_information_event_cluster
    (high_value DESC, priority_score DESC, last_published_at DESC);

CREATE TABLE IF NOT EXISTS cynexus_appl_market.market_information_event_member (
    cluster_id bigint NOT NULL REFERENCES cynexus_appl_market.market_information_event_cluster(id) ON DELETE CASCADE,
    source varchar(96) NOT NULL,
    source_record_id varchar(192) NOT NULL,
    published_at timestamptz NOT NULL,
    similarity numeric(6, 5) NOT NULL DEFAULT 1,
    created_at timestamptz NOT NULL DEFAULT now(),
    PRIMARY KEY (source, source_record_id)
);

CREATE INDEX IF NOT EXISTS idx_market_information_event_member_cluster
    ON cynexus_appl_market.market_information_event_member (cluster_id, published_at DESC);

