\set ON_ERROR_STOP on

CREATE SCHEMA IF NOT EXISTS cynexus_appl_life;

CREATE TABLE IF NOT EXISTS cynexus_appl_life.workout_request (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    owner_key text NOT NULL CHECK (btrim(owner_key) <> ''),
    resource text NOT NULL CHECK (resource IN ('plan', 'session', 'measurement')),
    idempotency_key text NOT NULL CHECK (length(btrim(idempotency_key)) BETWEEN 1 AND 128),
    entity_id text NOT NULL CHECK (btrim(entity_id) <> ''),
    request_fingerprint text NOT NULL CHECK (length(btrim(request_fingerprint)) = 64),
    created_at timestamptz NOT NULL DEFAULT now(),
    deleted_at timestamptz,
    CONSTRAINT uk_workout_request_key UNIQUE (owner_key, resource, idempotency_key)
);

CREATE INDEX IF NOT EXISTS idx_workout_request_entity
    ON cynexus_appl_life.workout_request (owner_key, resource, entity_id)
    WHERE deleted_at IS NULL;

COMMENT ON TABLE cynexus_appl_life.workout_request IS
    'Durable owner-scoped idempotency ledger for Workout writes.';

INSERT INTO cynexus_appl_life.workout_request
    (owner_key, resource, idempotency_key, entity_id, request_fingerprint, created_at, deleted_at)
SELECT owner_key, 'plan', idempotency_key, id::text, metadata->>'requestFingerprint', created_at, deleted_at
FROM cynexus_appl_life.workout_plan
WHERE idempotency_key IS NOT NULL AND length(metadata->>'requestFingerprint') = 64
ON CONFLICT (owner_key, resource, idempotency_key) DO NOTHING;

