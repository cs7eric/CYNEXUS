CREATE TABLE IF NOT EXISTS cynexus_appl_ai.ai_agent_write_command (
    id bigint PRIMARY KEY,
    command_no varchar(64) NOT NULL UNIQUE,
    owner_key varchar(128) NOT NULL,
    tenant_key varchar(128) NOT NULL,
    principal_key varchar(128) NOT NULL,
    conversation_no varchar(64),
    run_no varchar(64),
    tool_code varchar(128) NOT NULL,
    arguments_json jsonb NOT NULL,
    argument_digest varchar(128) NOT NULL,
    confirmation_token_hash varchar(128) NOT NULL,
    status varchar(32) NOT NULL,
    expires_at timestamptz NOT NULL,
    confirmed_at timestamptz,
    executed_at timestamptz,
    result_json jsonb,
    error_message varchar(500),
    created_at timestamptz NOT NULL DEFAULT now(),
    updated_at timestamptz NOT NULL DEFAULT now(),
    deleted_at timestamptz
);

CREATE TABLE IF NOT EXISTS cynexus_appl_ai.ai_agent_write_audit (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    command_no varchar(64) NOT NULL,
    owner_key varchar(128) NOT NULL,
    action varchar(32) NOT NULL,
    status varchar(32) NOT NULL,
    tool_code varchar(128),
    argument_digest varchar(128),
    result_json jsonb,
    error_message varchar(500),
    occurred_at timestamptz NOT NULL DEFAULT now()
);

CREATE INDEX IF NOT EXISTS idx_ai_agent_write_audit_owner_time
    ON cynexus_appl_ai.ai_agent_write_audit (owner_key, occurred_at DESC);
