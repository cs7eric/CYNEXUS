CREATE SCHEMA IF NOT EXISTS cynexus_appl_market;

CREATE TABLE IF NOT EXISTS cynexus_appl_market.mkt_style_sector_snapshot
(
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    trade_date date NOT NULL,
    name text NOT NULL,
    rank_by_change integer,
    change_pct numeric(12,6),
    valid_size integer NOT NULL DEFAULT 0,
    sample_size integer NOT NULL DEFAULT 0,
    source text NOT NULL DEFAULT 'tencent.qt',
    payload jsonb NOT NULL DEFAULT '{}'::jsonb,
    ingested_at timestamptz NOT NULL DEFAULT now(),
    updated_at timestamptz NOT NULL DEFAULT now(),
    deleted_at timestamptz
);

CREATE UNIQUE INDEX IF NOT EXISTS uk_mkt_style_sector_snapshot_key_alive
    ON cynexus_appl_market.mkt_style_sector_snapshot (trade_date, name, source)
    WHERE deleted_at IS NULL;

CREATE INDEX IF NOT EXISTS idx_mkt_style_sector_snapshot_date_rank_alive
    ON cynexus_appl_market.mkt_style_sector_snapshot (trade_date DESC, rank_by_change ASC)
    WHERE deleted_at IS NULL;
