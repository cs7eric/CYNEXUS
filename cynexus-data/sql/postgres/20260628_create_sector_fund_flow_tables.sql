CREATE SCHEMA IF NOT EXISTS cynexus_appl_market;
CREATE TABLE IF NOT EXISTS cynexus_appl_market.sector_fund_flow_capture_batches
(
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    scope text NOT NULL DEFAULT 'industry',
    trade_date date NOT NULL,
    source_type text NOT NULL DEFAULT 'crawler',
    status text NOT NULL DEFAULT 'success',
    source text NOT NULL DEFAULT 'ths.10jqka.com.cn',
    total_pages integer,
    row_count integer NOT NULL DEFAULT 0,
    page_row_counts jsonb NOT NULL DEFAULT '[]'::jsonb,
    fetched_at timestamptz NOT NULL DEFAULT now(),
    extra jsonb NOT NULL DEFAULT '{}'::jsonb,
    remark text,
    created_at timestamptz NOT NULL DEFAULT now(),
    updated_at timestamptz NOT NULL DEFAULT now(),
    deleted_at timestamptz,
    CONSTRAINT ck_sector_fund_flow_capture_batches_scope CHECK (scope IN ('industry', 'concept')),
    CONSTRAINT ck_sector_fund_flow_capture_batches_source_type CHECK (source_type IN ('crawler', 'json_import')),
    CONSTRAINT ck_sector_fund_flow_capture_batches_status CHECK (status IN ('success', 'partial', 'failed'))
);

CREATE UNIQUE INDEX IF NOT EXISTS uk_sector_fund_flow_capture_batches_scope_trade_date_alive
    ON cynexus_appl_market.sector_fund_flow_capture_batches (scope, trade_date)
    WHERE deleted_at IS NULL;

CREATE INDEX IF NOT EXISTS idx_sector_fund_flow_capture_batches_scope_fetched_at
    ON cynexus_appl_market.sector_fund_flow_capture_batches (scope, fetched_at DESC)
    WHERE deleted_at IS NULL;

CREATE TABLE IF NOT EXISTS cynexus_appl_market.sector_fund_flow_daily_snapshots
(
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    batch_id bigint NOT NULL REFERENCES cynexus_appl_market.sector_fund_flow_capture_batches(id) ON DELETE CASCADE,
    scope text NOT NULL DEFAULT 'industry',
    trade_date date NOT NULL,
    sector_code text,
    sector_name text NOT NULL,
    rank integer,
    change_pct numeric(12,6),
    inflow numeric(24,6),
    outflow numeric(24,6),
    net numeric(24,6),
    company_count integer,
    leader_stock text,
    leader_change numeric(12,6),
    leader_price numeric(24,6),
    source text NOT NULL DEFAULT 'ths.10jqka.com.cn',
    source_type text NOT NULL DEFAULT 'crawler',
    captured_at timestamptz NOT NULL DEFAULT now(),
    extra jsonb NOT NULL DEFAULT '{}'::jsonb,
    remark text,
    created_at timestamptz NOT NULL DEFAULT now(),
    updated_at timestamptz NOT NULL DEFAULT now(),
    deleted_at timestamptz,
    CONSTRAINT ck_sector_fund_flow_daily_snapshots_scope CHECK (scope IN ('industry', 'concept')),
    CONSTRAINT ck_sector_fund_flow_daily_snapshots_source_type CHECK (source_type IN ('crawler', 'json_import'))
);

CREATE UNIQUE INDEX IF NOT EXISTS uk_sector_fund_flow_daily_snapshots_scope_trade_date_sector_alive
    ON cynexus_appl_market.sector_fund_flow_daily_snapshots (scope, trade_date, sector_name)
    WHERE deleted_at IS NULL;

CREATE INDEX IF NOT EXISTS idx_sector_fund_flow_daily_snapshots_scope_trade_date_net
    ON cynexus_appl_market.sector_fund_flow_daily_snapshots (scope, trade_date, net DESC, rank ASC)
    WHERE deleted_at IS NULL;

CREATE INDEX IF NOT EXISTS idx_sector_fund_flow_daily_snapshots_scope_sector_trade_date
    ON cynexus_appl_market.sector_fund_flow_daily_snapshots (scope, sector_name, trade_date DESC)
    WHERE deleted_at IS NULL;
