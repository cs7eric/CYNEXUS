CREATE SCHEMA IF NOT EXISTS cynexus_appl_market;

CREATE TABLE IF NOT EXISTS cynexus_appl_market.market_limit_daily_snapshots
(
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    trade_date date NOT NULL,
    limit_up_count integer,
    limit_down_count integer,
    touched_count integer,
    broken_count integer,
    break_board_rate numeric(6,4),
    max_streak_height integer,
    promotion_overall_rate numeric(10,4),
    sentiment_level varchar(32),
    sentiment_text text,
    stock_count integer,
    market_status varchar(32),
    data_status varchar(32),
    source varchar(64),
    extra jsonb NOT NULL DEFAULT '{}'::jsonb,
    created_at timestamptz NOT NULL DEFAULT now(),
    updated_at timestamptz NOT NULL DEFAULT now(),
    deleted_at timestamptz
);

CREATE UNIQUE INDEX IF NOT EXISTS uk_market_limit_daily_snapshots_trade_date
    ON cynexus_appl_market.market_limit_daily_snapshots (trade_date)
    WHERE deleted_at IS NULL;

CREATE INDEX IF NOT EXISTS idx_market_limit_daily_snapshots_trade_date_desc
    ON cynexus_appl_market.market_limit_daily_snapshots (trade_date DESC)
    WHERE deleted_at IS NULL;

CREATE TABLE IF NOT EXISTS cynexus_appl_market.market_limit_daily_stocks
(
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    trade_date date NOT NULL,
    code varchar(32) NOT NULL,
    name varchar(128),
    category varchar(32) NOT NULL,
    streak integer,
    change_pct numeric(12,6),
    limit_up_price numeric(20,6),
    limit_down_price numeric(20,6),
    created_at timestamptz NOT NULL DEFAULT now(),
    updated_at timestamptz NOT NULL DEFAULT now(),
    deleted_at timestamptz
);

CREATE UNIQUE INDEX IF NOT EXISTS uk_market_limit_daily_stocks_trade_date_code
    ON cynexus_appl_market.market_limit_daily_stocks (trade_date, code)
    WHERE deleted_at IS NULL;

CREATE INDEX IF NOT EXISTS idx_market_limit_daily_stocks_date_category_alive
    ON cynexus_appl_market.market_limit_daily_stocks (trade_date DESC, category, streak DESC NULLS LAST)
    WHERE deleted_at IS NULL;
