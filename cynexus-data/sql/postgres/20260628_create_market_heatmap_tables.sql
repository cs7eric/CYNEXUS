CREATE SCHEMA IF NOT EXISTS cynexus_appl_market;

CREATE TABLE IF NOT EXISTS cynexus_appl_market.mkt_heatmap_snapshot
(
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    snapshot_date date NOT NULL,
    kind text NOT NULL,
    source text NOT NULL,
    payload jsonb NOT NULL,
    item_count integer NOT NULL DEFAULT 0,
    generated_at timestamptz NOT NULL DEFAULT now(),
    created_at timestamptz NOT NULL DEFAULT now(),
    updated_at timestamptz NOT NULL DEFAULT now(),
    deleted_at timestamptz
);

CREATE UNIQUE INDEX IF NOT EXISTS uk_mkt_heatmap_snapshot_key_alive
    ON cynexus_appl_market.mkt_heatmap_snapshot (snapshot_date, kind, source)
    WHERE deleted_at IS NULL;

CREATE INDEX IF NOT EXISTS idx_mkt_heatmap_snapshot_alive
    ON cynexus_appl_market.mkt_heatmap_snapshot (snapshot_date DESC, kind, source)
    WHERE deleted_at IS NULL;
