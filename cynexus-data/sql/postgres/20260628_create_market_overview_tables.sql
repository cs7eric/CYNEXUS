CREATE SCHEMA IF NOT EXISTS cynexus_appl_market;

CREATE TABLE IF NOT EXISTS cynexus_appl_market.market_overview_snapshots
(
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    trade_date date NOT NULL,
    total_amount numeric(18,4),
    total_volume numeric(18,4),
    rising_count integer,
    falling_count integer,
    flat_count integer,
    limit_up_count integer,
    limit_down_count integer,
    stock_count integer,
    main_net_inflow numeric(18,4),
    super_large_net_inflow numeric(18,4),
    large_net_inflow numeric(18,4),
    medium_net_inflow numeric(18,4),
    small_net_inflow numeric(18,4),
    main_net_inflow_ratio numeric(8,4),
    super_large_net_ratio numeric(8,4),
    large_net_ratio numeric(8,4),
    medium_net_ratio numeric(8,4),
    small_net_ratio numeric(8,4),
    source text,
    is_manual_override boolean NOT NULL DEFAULT false,
    manual_updated_at timestamptz,
    extra jsonb NOT NULL DEFAULT '{}'::jsonb,
    created_at timestamptz NOT NULL DEFAULT now(),
    updated_at timestamptz NOT NULL DEFAULT now(),
    deleted_at timestamptz
);

CREATE UNIQUE INDEX IF NOT EXISTS uk_market_overview_snapshots_trade_date_alive
    ON cynexus_appl_market.market_overview_snapshots (trade_date)
    WHERE deleted_at IS NULL;

CREATE INDEX IF NOT EXISTS idx_market_overview_snapshots_trade_date_alive
    ON cynexus_appl_market.market_overview_snapshots (trade_date DESC)
    WHERE deleted_at IS NULL;

ALTER TABLE cynexus_appl_market.market_overview_snapshots
    ALTER COLUMN source TYPE text;

CREATE TABLE IF NOT EXISTS cynexus_appl_market.mkt_overview_detail_snapshot
(
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    trade_date date NOT NULL,
    benchmark_code text NOT NULL,
    source_table text NOT NULL,
    payload jsonb NOT NULL DEFAULT '{}'::jsonb,
    source text NOT NULL DEFAULT 'python',
    generated_at timestamptz NOT NULL DEFAULT now(),
    created_at timestamptz NOT NULL DEFAULT now(),
    updated_at timestamptz NOT NULL DEFAULT now(),
    deleted_at timestamptz
);

CREATE UNIQUE INDEX IF NOT EXISTS uk_mkt_overview_detail_snapshot_key_alive
    ON cynexus_appl_market.mkt_overview_detail_snapshot (trade_date, benchmark_code, source_table)
    WHERE deleted_at IS NULL;

CREATE INDEX IF NOT EXISTS idx_mkt_overview_detail_snapshot_alive
    ON cynexus_appl_market.mkt_overview_detail_snapshot (trade_date DESC, benchmark_code)
    WHERE deleted_at IS NULL;
